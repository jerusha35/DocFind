package com.docufind.db;

import com.docufind.config.AppConfig;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.logging.Level;
import java.util.logging.Logger;

/**
 * Manages JDBC connections to the Oracle database.
 */
public class DBConnection {
    private static final Logger LOGGER = Logger.getLogger(DBConnection.class.getName());

    static {
        try {
            // Explicitly load Oracle JDBC Driver
            Class.forName("oracle.jdbc.OracleDriver");
            LOGGER.info("Oracle JDBC Driver loaded successfully.");
        } catch (ClassNotFoundException e) {
            LOGGER.log(Level.SEVERE, "Oracle JDBC Driver not found on classpath!", e);
        }
    }

    /**
     * Obtains a new database connection using configuration settings.
     *
     * @return Connection to Oracle database
     * @throws SQLException if a database access error occurs
     */
    public static Connection getConnection() throws SQLException {
        String url = AppConfig.get("db.url");
        String user = AppConfig.get("db.user");
        String password = AppConfig.get("db.password");
        return DriverManager.getConnection(url, user, password);
    }

    /**
     * Tests connectivity to the Oracle database.
     *
     * @return true if connection succeeds and ping returns valid, false otherwise.
     */
    public static boolean testConnection() {
        try (Connection conn = getConnection()) {
            return conn != null && !conn.isClosed() && conn.isValid(5);
        } catch (Exception e) {
            LOGGER.log(Level.WARNING, "Oracle database connection test failed: " + e.getMessage());
            return false;
        }
    }

    /**
     * Initializes the database schema automatically if tables do not exist.
     */
    public static void initializeSchema() {
        String[] statements = new String[]{
            // Sequence creation
            "BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_APP_USERS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            "BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_INDEXED_FOLDERS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            "BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_DOCUMENTS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            "BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_SAVED_SEARCHES START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            "BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_SEARCH_HISTORY START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            "BEGIN EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_INDEXING_LOGS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            
            // APP_USERS
            "BEGIN EXECUTE IMMEDIATE 'CREATE TABLE APP_USERS (USER_ID NUMBER PRIMARY KEY, USERNAME VARCHAR2(100) NOT NULL UNIQUE, EMAIL VARCHAR2(255) NOT NULL UNIQUE, PASSWORD_HASH VARCHAR2(256) NOT NULL, PASSWORD_SALT VARCHAR2(128) NOT NULL, ROLE VARCHAR2(20) DEFAULT ''USER'' NOT NULL CHECK (ROLE IN (''ADMIN'', ''USER'')), CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, IS_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (IS_ACTIVE IN (0, 1)))'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            
            // INDEXED_FOLDERS
            "BEGIN EXECUTE IMMEDIATE 'CREATE TABLE INDEXED_FOLDERS (FOLDER_ID NUMBER PRIMARY KEY, USER_ID NUMBER NOT NULL, FOLDER_PATH VARCHAR2(1000) NOT NULL, ADDED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, LAST_INDEXED_AT TIMESTAMP, INDEX_STATUS VARCHAR2(50) DEFAULT ''PENDING'' NOT NULL, CONSTRAINT FK_FOLDERS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS(USER_ID) ON DELETE CASCADE, CONSTRAINT UQ_USER_FOLDER UNIQUE (USER_ID, FOLDER_PATH))'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            
            // DOCUMENTS
            "BEGIN EXECUTE IMMEDIATE 'CREATE TABLE DOCUMENTS (DOCUMENT_ID NUMBER PRIMARY KEY, USER_ID NUMBER NOT NULL, FOLDER_ID NUMBER NOT NULL, FILE_NAME VARCHAR2(500) NOT NULL, FILE_PATH VARCHAR2(1000) NOT NULL, FILE_EXTENSION VARCHAR2(50), FILE_SIZE NUMBER, LAST_MODIFIED TIMESTAMP, SHA256_HASH VARCHAR2(64), EXTRACTED_TEXT CLOB, INDEXED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, INDEX_STATUS VARCHAR2(50) DEFAULT ''INDEXED'' NOT NULL, CONSTRAINT FK_DOCS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS(USER_ID) ON DELETE CASCADE, CONSTRAINT FK_DOCS_FOLDER FOREIGN KEY (FOLDER_ID) REFERENCES INDEXED_FOLDERS(FOLDER_ID) ON DELETE CASCADE, CONSTRAINT UQ_USER_FILE_PATH UNIQUE (USER_ID, FILE_PATH))'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            
            // DOCUMENTS Indexes
            "BEGIN EXECUTE IMMEDIATE 'CREATE INDEX IDX_DOCS_USER_NAME ON DOCUMENTS(USER_ID, FILE_NAME)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 AND SQLCODE != -1408 THEN RAISE; END IF; END;",
            "BEGIN EXECUTE IMMEDIATE 'CREATE INDEX IDX_DOCS_USER_EXT ON DOCUMENTS(USER_ID, FILE_EXTENSION)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 AND SQLCODE != -1408 THEN RAISE; END IF; END;",
            "BEGIN EXECUTE IMMEDIATE 'CREATE INDEX IDX_DOCS_USER_FOLDER ON DOCUMENTS(USER_ID, FOLDER_ID)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 AND SQLCODE != -1408 THEN RAISE; END IF; END;",

            // SAVED_SEARCHES
            "BEGIN EXECUTE IMMEDIATE 'CREATE TABLE SAVED_SEARCHES (SEARCH_ID NUMBER PRIMARY KEY, USER_ID NUMBER NOT NULL, SEARCH_NAME VARCHAR2(200) NOT NULL, SEARCH_QUERY VARCHAR2(500) NOT NULL, SEARCH_MODE VARCHAR2(50) NOT NULL, FILTER_SETTINGS VARCHAR2(1000), CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, CONSTRAINT FK_SAVED_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS(USER_ID) ON DELETE CASCADE)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            
            // SEARCH_HISTORY
            "BEGIN EXECUTE IMMEDIATE 'CREATE TABLE SEARCH_HISTORY (HISTORY_ID NUMBER PRIMARY KEY, USER_ID NUMBER NOT NULL, SEARCH_QUERY VARCHAR2(500) NOT NULL, SEARCH_MODE VARCHAR2(50) NOT NULL, RESULT_COUNT NUMBER DEFAULT 0 NOT NULL, SEARCHED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, CONSTRAINT FK_HISTORY_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS(USER_ID) ON DELETE CASCADE)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            "BEGIN EXECUTE IMMEDIATE 'CREATE INDEX IDX_HIST_USER_DATE ON SEARCH_HISTORY(USER_ID, SEARCHED_AT DESC)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 AND SQLCODE != -1408 THEN RAISE; END IF; END;",
            
            // INDEXING_LOGS
            "BEGIN EXECUTE IMMEDIATE 'CREATE TABLE INDEXING_LOGS (LOG_ID NUMBER PRIMARY KEY, USER_ID NUMBER NOT NULL, FOLDER_ID NUMBER, FILE_PATH VARCHAR2(1000), STATUS VARCHAR2(50) NOT NULL, ERROR_MESSAGE VARCHAR2(4000), LOGGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, CONSTRAINT FK_LOGS_USER FOREIGN KEY (USER_ID) REFERENCES APP_USERS(USER_ID) ON DELETE CASCADE)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF; END;",
            "BEGIN EXECUTE IMMEDIATE 'CREATE INDEX IDX_LOGS_USER_DATE ON INDEXING_LOGS(USER_ID, LOGGED_AT DESC)'; EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 AND SQLCODE != -1408 THEN RAISE; END IF; END;"
        };

        try (Connection conn = getConnection(); Statement stmt = conn.createStatement()) {
            for (String sql : statements) {
                try {
                    stmt.execute(sql);
                } catch (SQLException ex) {
                    LOGGER.log(Level.WARNING, "Schema init warning on statement: " + ex.getMessage());
                }
            }
            LOGGER.info("DocuFind database schema checked/initialized successfully.");
        } catch (SQLException e) {
            LOGGER.log(Level.SEVERE, "Database connection error during schema initialization: " + e.getMessage(), e);
        }
    }
}
